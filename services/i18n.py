def tr(text: str) -> str:
    """Translate a known interface string; never send text to a remote service."""
    if st.session_state.get(LANGUAGE_KEY, False):
        if text in _TRANSLATIONS:
            return _TRANSLATIONS[text]
        for pattern, replacement in _DYNAMIC:
            if re.fullmatch(pattern, text, re.DOTALL):
                return re.sub(pattern, replacement, text, flags=re.DOTALL)
    return text
